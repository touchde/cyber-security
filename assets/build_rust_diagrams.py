"""Generate the Rust course's diagrams, in its iron and rust-orange palette, into assets/diagrams/.

    python3 assets/build_rust_diagrams.py

They are written to diagrams/22-rust/.
"""
from diagram_kit import Kit

k = Kit(folder="22-rust", primary="#A9380F", tint="#FBF0E9", ink="#1E1714", muted="#61534B", line="#F0D8C9",
        sans="'Bricolage Grotesque', 'Helvetica Neue', Arial, sans-serif", mono="'Reddit Mono', Menlo, monospace", accent="#E2622F")
RED, RED_TINT, GREEN, GREEN_TINT = "#B3261E", "#FCE8E6", "#1B7A44", "#E3F5EC"


def menu_reload():
    """The same mistake in C++ (a crash, sometimes) and in Rust (a compile error, always)."""
    b = [k.text(40, 140, "C++: the program runs, and sometimes crashes", 20, RED, 700, "start")]
    cpp = [("Point at the first item", "of today's menu"), ("The new menu arrives", "the old menu's memory is freed"),
           ("Read the first item", "through the old pointer")]
    for i, (name, sub) in enumerate(cpp):
        x = 40 + i * 270
        b.append(k.node(x, 160, 230, 96, name, sub))
        if i:
            b.append(k.arrow(x - 38, 208, x - 2, 208))
    b += [k.arrow(40 + 2 * 270 + 232, 208, 40 + 3 * 270 - 2, 208),
          k.node(40 + 3 * 270, 160, 230, 96, "Wrong data or a crash", "once a week, on some phones", RED_TINT, RED, RED, RED),
          k.text(40, 320, "Rust: the program is never built", 20, GREEN, 700, "start")]
    rust = [("Borrow the first item", "let first = &menu[0];"), ("Try to clear the menu", "menu.clear();")]
    for i, (name, sub) in enumerate(rust):
        x = 40 + i * 270
        b.append(k.node(x, 340, 230, 96, name, sub))
        if i:
            b.append(k.arrow(x - 38, 388, x - 2, 388))
    b += [k.arrow(40 + 270 + 232, 388, 40 + 2 * 270 - 2, 388),
          k.box(40 + 2 * 270, 340, 500, 96, GREEN_TINT, GREEN),
          k.text(40 + 2 * 270 + 250, 380, "Compile error E0502", 22, GREEN, 700),
          k.text(40 + 2 * 270 + 250, 410, "the mistake is fixed before any customer sees it", 17, GREEN),
          k.text(40, 500, "Both programs make the same mistake. C++ finds it on a customer's phone; Rust finds it on Vanna's laptop.", 19, k.ink, 700, "start")]
    k.svg("menu-reload-crash", 1120, 540, "The menu-reload crash", "The same mistake, in C++ and in Rust", "".join(b))


def who_frees():
    """Four ways to give memory back, and when each one decides."""
    cols = [("C and C++", "You do", "free() and delete, by hand", ("Easy to get wrong", "forget: a leak; too early: a crash"), "#FFFFFF"),
            ("Kotlin and Dart", "A garbage collector", "finds unused memory while the app runs", ("Short pauses", "and more memory in use"), "#FFFFFF"),
            ("Swift", "ARC", "counts references while the app runs", ("A small cost each time", "and cycles can leak"), "#FFFFFF"),
            ("Rust", "The compiler", "adds the free where the owner ends", ("No cost at run time", "but stricter rules to learn"), k.tint)]
    b = [k.text(40, 228, "Who frees it?", 17, k.muted, 700, "start"), k.text(40, 330, "The cost", 17, k.muted, 700, "start")]
    for i, (lang, who, how, cost, fill) in enumerate(cols):
        x = 170 + i * 240
        b += [k.box(x, 110, 220, 50, k.primary if i == 3 else "#FFFFFF", k.primary),
              k.text(x + 110, 142, lang, 20, "#FFFFFF" if i == 3 else k.ink, 700),
              k.node(x, 172, 220, 100, who, how, fill),
              k.node(x, 284, 220, 90, cost[0], cost[1], fill)]
    b += [k.text(40, 430, "Rust decides when memory is freed while it compiles, so nothing has to watch the memory while the app runs.", 19, k.ink, 700, "start")]
    k.svg("who-frees-memory", 1140, 470, "Who gives memory back?", "Four answers to the same question", "".join(b))


def one_core():
    """One Rust core, called from every app through generated bindings."""
    apps = [("Android", "Kotlin"), ("iOS", "Swift"), ("Flutter", "Dart"), ("React Native", "TypeScript"), ("Website", "WebAssembly")]
    b = []
    for i, (name, lang) in enumerate(apps):
        x = 40 + i * 212
        b += [k.node(x, 120, 192, 84, name, lang), k.arrow(x + 96, 268, x + 96, 206)]
    b += [k.box(40, 270, 1040, 60, "#FFFFFF", k.line), k.text(560, 307, "Bindings, generated by tools such as UniFFI and wasm-bindgen", 19, k.muted, 600),
          k.arrow(560, 380, 560, 332),
          k.node(330, 382, 460, 100, "The Mina Coffee core, in Rust", "prices, member discounts, and offline orders", k.tint),
          k.text(40, 540, "The price rules are written once, tested once, and give the same answer in every app.", 19, k.ink, 700, "start")]
    k.svg("one-core-every-app", 1120, 580, "One core for every app", "How a shared Rust library reaches each platform", "".join(b))


for make in (menu_reload, who_frees, one_core):
    make()
print("diagrams written")
